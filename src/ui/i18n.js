const fill = (s, vars) => (vars ? String(s).replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m)) : String(s));

/** The label for `key` in the page's language ({name} placeholders from vars); an unknown key comes back as itself. */
export function t(key, vars) {
  const e = DICT[key];
  if (!e) return key;
  return fill(isZh ? e[1] : e[0], vars);
}

const PREFIX = { weapon: 'w.', sub: 's.', special: 'sp.', map: 'map.', team: 'team.', kind: 'kind.', diff: 'diff.', rank: 'rank.', wblurb: 'wb.', sblurb: 'sb.', spblurb: 'spb.' };
/** A game name in the page's language: gameName('weapon', 'shooter', 'Spritzer') → 喷喷枪 (en, or an unknown id: en). */
export function gameName(kind, id, en = '') {
  if (!isZh) return en || (DICT[(PREFIX[kind] || '') + id] || [])[0] || String(id ?? '');
  const e = DICT[(PREFIX[kind] || '') + id];
  return e ? e[1] : en || String(id ?? '');
}
/** A team's ink name ('Tangerine' → 橘子队); names outside the palettes (a room's own) come back as they are. */
export function teamName(name) {
  if (!isZh || !name) return name || '';
  const n = String(name);
  const e = DICT['team.' + n.charAt(0).toUpperCase() + n.slice(1).toLowerCase()];
  return e ? e[1] : name;
}
